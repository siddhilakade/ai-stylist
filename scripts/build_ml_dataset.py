"""Generate the pairwise compatibility training set.

The dataset has no user interactions and no compatibility labels, so labels here
are SYNTHETIC - produced by this project's own rule engine. They are not user
behaviour, clicks, purchases or expert annotation.

That has a consequence worth stating: a model trained on these is learning to
reproduce a heuristic. The experiment is still worth running (the model sees only
raw attributes, so it must induce the heuristic rather than copy it), but it
can't show the model learned real taste. That's what human_validation.csv is for.

Run:  python scripts/build_ml_dataset.py
Out:  data/ml_training/compatibility_pairs.csv
"""

from __future__ import annotations

import hashlib
import sys
from itertools import combinations
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.compatibility import is_hard_clash, pair_compatibility  # noqa: E402
from src.data import catalog_records  # noqa: E402
from src.ml.features import canonical_order, pair_features  # noqa: E402

OUT_DIR = ROOT / "data" / "ml_training"
OUT_PATH = OUT_DIR / "compatibility_pairs.csv"

# Pairs are only meaningful across different outfit slots - two shirts are not a
# "pair" in outfit terms. Accessories pair with everything.
VALID_SLOT_PAIRS = {
    frozenset(pair) for pair in [
        ("top", "bottom"), ("top", "footwear"), ("top", "outerwear"),
        ("top", "accessory"), ("bottom", "footwear"), ("bottom", "outerwear"),
        ("bottom", "accessory"), ("footwear", "outerwear"),
        ("footwear", "accessory"), ("outerwear", "accessory"),
        ("onepiece", "footwear"), ("onepiece", "outerwear"),
        ("onepiece", "accessory"),
    ]
}

# A pair is labelled compatible when the rule engine's weighted score clears this
# bar. 0.70 sits above "one neutral + adjacent formality" and below "clearly
# coordinated", and produces a roughly balanced dataset - checked in the run
# summary, not assumed.
COMPATIBLE_THRESHOLD = 0.70

TARGET_PAIRS = 24_000


def deterministic_sample(pairs: list[tuple[dict, dict]], limit: int) -> list[tuple[dict, dict]]:
    """Stable subsample: hash the id pair, keep the lowest hashes.

    Deterministic across machines and runs, unlike random.sample with a seed,
    which depends on Python's PRNG implementation.
    """
    if len(pairs) <= limit:
        return pairs

    def key(pair: tuple[dict, dict]) -> str:
        a, b = pair
        return hashlib.sha256(f"{a['id']}-{b['id']}".encode()).hexdigest()

    return sorted(pairs, key=key)[:limit]


def main() -> None:
    products = list(catalog_records())
    print(f"Catalog: {len(products)} products")

    candidate_pairs = [
        (a, b) for a, b in combinations(products, 2)
        if frozenset((a["outfit_slot"], b["outfit_slot"])) in VALID_SLOT_PAIRS
        # Menswear/womenswear pairs are never assembled into one outfit, so
        # training on them would teach the model a distinction the recommender
        # already enforces upstream as a hard constraint.
        and not ({a["gender"], b["gender"]} == {"Men", "Women"})
    ]
    print(f"Valid cross-slot pairs: {len(candidate_pairs):,}")

    sampled = deterministic_sample(candidate_pairs, TARGET_PAIRS)
    print(f"Sampled: {len(sampled):,}")

    rows = []
    for item_a, item_b in sampled:
        a, b = canonical_order(item_a, item_b)
        score = pair_compatibility(a, b)
        rows.append({
            "id_a": int(a["id"]), "id_b": int(b["id"]),
            **pair_features(a, b),
            # Kept for analysis and for the rule baseline. NEVER used as a model
            # feature - see src/ml/features.py.
            "rule_score": score,
            "hard_clash": is_hard_clash(a, b),
            "compatible": int(score >= COMPATIBLE_THRESHOLD),
        })

    frame = pd.DataFrame(rows)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    frame.to_csv(OUT_PATH, index=False)

    positives = int(frame["compatible"].sum())
    print(f"\nWrote {OUT_PATH.relative_to(ROOT)}")
    print(f"  rows          : {len(frame):,}")
    print(f"  compatible=1  : {positives:,} ({positives / len(frame):.1%})")
    print(f"  compatible=0  : {len(frame) - positives:,}")
    print(f"  hard clashes  : {int(frame['hard_clash'].sum()):,}")
    print(f"  distinct articleType_a: {frame['articleType_a'].nunique()}")
    print(f"  distinct articleType_b: {frame['articleType_b'].nunique()}")
    print("\nLABELS ARE SYNTHETIC/HEURISTIC - generated by src/compatibility.py, "
          "not observed from users.")


if __name__ == "__main__":
    main()
